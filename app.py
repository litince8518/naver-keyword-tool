def get_month_suggestions(month=None, n_seasonal=2, n_evergreen=3):
    """이번 달 추천 소재: 시즌 n개 + 상시 n개. 다음 달 시즌도 미리보기로."""
    if month is None:
        month = datetime.date.today().month
    nxt = month % 12 + 1
    return {
        "month": month,
        "seasonal_now": SEASONAL.get(month, [])[:n_seasonal],
        "seasonal_next": SEASONAL.get(nxt, [])[:1],   # 다음 달 미리 써두기용 1개
        "evergreen": EVERGREEN[:n_evergreen],
    }


def render():
    """Streamlit 탭 본문. app_6.py에서 with tabs[-1]: topic_calendar.render()"""
    import streamlit as st

    st.subheader("🗓️ 소재 캘린더 — 육아 가정 돈 정보")
    st.caption("두딸파파 전용 · '이번 주 뭐 쓰지?'를 시즌 2개 + 상시 3개로 제안 "
               "· 금액/요율은 글 쓸 때 web_search로 재확인")

    months = ["1월","2월","3월","4월","5월","6월","7월","8월","9월","10월","11월","12월"]
    cur = datetime.date.today().month
    sel = st.selectbox("기준 월", months, index=cur - 1)
    month = months.index(sel) + 1

    data = get_month_suggestions(month)

    st.markdown(f"### 📌 {sel} 시즌 소재 (지금 터지는 돈 이슈)")
    if data["seasonal_now"]:
        for title, why in data["seasonal_now"]:
            st.markdown(f"- **{title}**  \n  └ {why}")
    else:
        st.write("등록된 시즌 소재 없음 — 상시 소재 활용")

    if data["seasonal_next"]:
        st.markdown("### ⏭️ 다음 달 미리 써두기")
        for title, why in data["seasonal_next"]:
            st.markdown(f"- **{title}**  \n  └ {why}")

    st.markdown("### ♻️ 상시 소재 (아무 때나 꾸준한 검색)")
    for title, why in data["evergreen"]:
        st.markdown(f"- **{title}**  \n  └ {why}")

    st.info("선택한 소재를 키워드 분석 탭에 넣어 검색량·경쟁도 검증 후 "
            "blog_ai_writer 프롬프트로 넘기세요. (발행은 항상 수동 — 자동발행 금지)")


